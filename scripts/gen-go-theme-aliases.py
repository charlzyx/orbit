#!/usr/bin/env python3
"""Preserve the pinned Rust baseline's accepted persisted palette identifiers."""
from pathlib import Path
import re
root=Path(__file__).resolve().parent.parent
source=(root/'crates/orbit-pi/src/theme.rs').read_text()
source=source.split('pub fn parse(raw: &str)')[1].split('/// Human label')[0]
ids={'Orbit':'orbit','OrbitLight':'orbit-light','OrbitPaper':'orbit-paper','OrbitContrast':'orbit-contrast','OrbitDarker':'orbit-darker','OrbitCobalt':'orbit-cobalt','OrbitAzure':'orbit-azure','OrbitAzureLight':'orbit-azure-light','Flexoki':'flexoki','FlexokiLight':'flexoki-light'}
a={}
for match in re.finditer(r'((?:"[^"\n]+"[\s|]*)+)\s*=>\s*(?:\{\s*)?Some\(Self::(\w+)\)',source):
 for alias in re.findall(r'"([^"\n]+)"',match.group(1)): a[alias]=ids[match.group(2)]
assert len(a)>70, len(a)
out=['// Code generated by scripts/gen-go-theme-aliases.py; DO NOT EDIT.','package preferences','','var themeAliases = map[string]string{']
out += [f'\t"{k}": "{v}",' for k,v in sorted(a.items())]
out += ['}','','func themeAlias(value string) string { return themeAliases[value] }','']
(root/'internal/preferences/theme_aliases.go').write_text('\n'.join(out))
print(f'{len(a)} persisted palette aliases')
